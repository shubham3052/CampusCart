from django.db import models
from django.conf import settings


class DemandModelMetadata(models.Model):
    """
    Stores audit metadata, hyperparameters, and evaluation metrics for trained regression models.
    Provides transparency into which model version generated current forecasts.
    """
    model_name = models.CharField(max_length=100, default="RandomForestRegressor")
    model_version = models.CharField(max_length=50, unique=True, default="v1.0.0")
    model_type = models.CharField(max_length=50, default="REGRESSION")
    training_date = models.DateTimeField(auto_now_add=True)
    training_samples = models.PositiveIntegerField(default=0)
    features_used = models.JSONField(default=list)
    mae = models.FloatField(default=0.0, help_text="Mean Absolute Error on test split")
    rmse = models.FloatField(default=0.0, help_text="Root Mean Squared Error on test split")
    r2_score = models.FloatField(default=0.0, help_text="R-squared metric on test split")
    baseline_mae = models.FloatField(default=0.0, help_text="7-day moving average baseline MAE")
    data_start_date = models.DateField(null=True, blank=True)
    data_end_date = models.DateField(null=True, blank=True)
    model_file_path = models.CharField(max_length=255, blank=True)
    is_active = models.BooleanField(default=True)
    notes = models.TextField(blank=True)

    class Meta:
        db_table = 'demand_model_metadata'
        verbose_name = 'Demand Model Metadata'
        verbose_name_plural = 'Demand Model Metadata'
        ordering = ['-training_date']

    def __str__(self):
        return f"{self.model_name} [{self.model_version}] (MAE: {self.mae}, R²: {self.r2_score})"


class DemandPrediction(models.Model):
    """
    Stationery demand forecasts generated by ML regression models.
    Belongs to a shop and product combination for a targeted future date or horizon.
    """
    class ForecastHorizon(models.TextChoices):
        DAILY = 'DAILY', 'Daily Forecast'
        HORIZON_7D = '7_DAYS', 'Next 7 Days Aggregated'
        HORIZON_30D = '30_DAYS', 'Next 30 Days Aggregated'

    shop = models.ForeignKey(
        'shops.Shop',
        on_delete=models.CASCADE,
        related_name='demand_predictions',
        db_index=True
    )
    product = models.ForeignKey(
        'products.Product',
        on_delete=models.CASCADE,
        related_name='demand_predictions',
        db_index=True
    )
    target_date = models.DateField(db_index=True, help_text="Target forecast date")
    forecast_horizon = models.CharField(
        max_length=20,
        choices=ForecastHorizon.choices,
        default=ForecastHorizon.DAILY,
        db_index=True
    )
    predicted_units = models.PositiveIntegerField(
        help_text="Predicted unit sales volume for this product on target_date or horizon"
    )
    confidence_score = models.DecimalField(
        max_digits=5,
        decimal_places=2,
        default=0.90,
        help_text="Confidence or accuracy score (e.g. 0.92 for 92%)"
    )
    confidence_interval_low = models.DecimalField(
        max_digits=8,
        decimal_places=2,
        default=0.00
    )
    confidence_interval_high = models.DecimalField(
        max_digits=8,
        decimal_places=2,
        default=0.00
    )
    associated_event = models.ForeignKey(
        'academics.AcademicCalendar',
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='predictions_affected'
    )
    model_name = models.CharField(max_length=60, default="RandomForestRegressor")
    model_version = models.CharField(max_length=30, default="v1.0.0")
    model_metadata = models.ForeignKey(
        DemandModelMetadata,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='predictions'
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = 'demand_predictions'
        verbose_name = 'Demand Prediction'
        verbose_name_plural = 'Demand Predictions'
        unique_together = ('shop', 'product', 'target_date', 'forecast_horizon')
        indexes = [
            models.Index(fields=['shop', 'target_date', 'forecast_horizon']),
            models.Index(fields=['product', 'target_date', 'forecast_horizon']),
        ]

    @property
    def prediction_date(self):
        return self.target_date

    @property
    def predicted_demand(self):
        return self.predicted_units

    @property
    def is_daily(self):
        return self.forecast_horizon == self.ForecastHorizon.DAILY

    @property
    def is_7d(self):
        return self.forecast_horizon == self.ForecastHorizon.HORIZON_7D

    @property
    def is_30d(self):
        return self.forecast_horizon == self.ForecastHorizon.HORIZON_30D

    def __str__(self):
        return f"{self.product.name} @ {self.shop.name} [{self.forecast_horizon}]: {self.predicted_units} units on {self.target_date}"


from decimal import Decimal


class PurchaseRecommendation(models.Model):
    """
    Intelligent inventory restocking advice generated by Smart Purchase Advisor.
    Calculates safety stock, reorder points, target stock, and vendor selections
    using authentic Step 17 regression forecasts and historical demand variability.
    """
    class Urgency(models.TextChoices):
        LOW = 'LOW', 'Low - Ample Stock Remaining'
        MEDIUM = 'MEDIUM', 'Medium - Routine Reorder'
        HIGH = 'HIGH', 'High - Reorder Soon (Upcoming Surge)'
        CRITICAL = 'CRITICAL', 'Critical - Imminent Stockout Risk'

    class Priority(models.TextChoices):
        CRITICAL = 'CRITICAL', 'Critical Priority'
        HIGH = 'HIGH', 'High Priority'
        MEDIUM = 'MEDIUM', 'Medium Priority'
        LOW = 'LOW', 'Low Priority'
        NONE = 'NONE', 'No Action Required'

    class Status(models.TextChoices):
        PENDING = 'PENDING', 'Pending Review'
        VIEWED = 'VIEWED', 'Viewed by Merchant'
        ACCEPTED = 'ACCEPTED', 'Accepted'
        ADJUSTED = 'ADJUSTED', 'Adjusted (Manual Override)'
        DISMISSED = 'DISMISSED', 'Dismissed'
        ORDER_CREATED = 'ORDER_CREATED', 'Purchase Order Created'
        EXPIRED = 'EXPIRED', 'Expired / Superseded'

    class PlanningHorizon(models.TextChoices):
        HORIZON_7D = '7_DAYS', 'Next 7 Days'
        HORIZON_30D = '30_DAYS', 'Next 30 Days'

    class ReorderStatus(models.TextChoices):
        REORDER_REQUIRED = 'REORDER_REQUIRED', 'Reorder Required'
        STOCK_ADEQUATE = 'STOCK_ADEQUATE', 'Stock Adequate'
        OUT_OF_STOCK = 'OUT_OF_STOCK', 'Out of Stock'
        LOW_STOCK = 'LOW_STOCK', 'Low Stock'
        OVERSTOCKED = 'OVERSTOCKED', 'Overstocked'

    class MovementType(models.TextChoices):
        FAST_MOVING = 'FAST_MOVING', 'Fast Moving Product'
        SLOW_MOVING = 'SLOW_MOVING', 'Slow Moving Product'
        NORMAL = 'NORMAL', 'Normal Velocity'
        POTENTIAL_DEAD_STOCK = 'POTENTIAL_DEAD_STOCK', 'Potential Dead Stock'

    class StockoutRisk(models.TextChoices):
        HIGH = 'HIGH', 'High Risk (Stockout Before Delivery)'
        MEDIUM = 'MEDIUM', 'Medium Risk'
        LOW = 'LOW', 'Low Risk'
        NONE = 'NONE', 'No Risk'

    class ReplenishmentTiming(models.TextChoices):
        ORDER_NOW = 'ORDER_NOW', 'Order Now (Immediate Procurement)'
        ORDER_SOON = 'ORDER_SOON', 'Order Soon (Approaching ROP)'
        MONITOR = 'MONITOR', 'Monitor Inventory'
        NO_PURCHASE_REQUIRED = 'NO_PURCHASE_REQUIRED', 'No Purchase Required'

    shop = models.ForeignKey(
        'shops.Shop',
        on_delete=models.CASCADE,
        related_name='purchase_recommendations',
        db_index=True
    )
    product = models.ForeignKey(
        'products.Product',
        on_delete=models.CASCADE,
        related_name='purchase_recommendations',
        db_index=True
    )
    supplier = models.ForeignKey(
        'inventory.Supplier',
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='advisor_recommendations'
    )
    current_stock = models.PositiveIntegerField(default=0)
    reserved_stock = models.PositiveIntegerField(default=0)
    available_stock = models.PositiveIntegerField(default=0)

    # ML Forecasts from Step 17
    predicted_demand_7d = models.PositiveIntegerField(default=0)
    predicted_demand_30d = models.PositiveIntegerField(default=0)
    planning_horizon = models.CharField(
        max_length=20,
        choices=PlanningHorizon.choices,
        default=PlanningHorizon.HORIZON_30D,
        db_index=True
    )
    predicted_demand = models.PositiveIntegerField(default=0)
    average_daily_demand = models.FloatField(default=0.0)
    demand_std_dev = models.FloatField(default=0.0)
    lead_time_days = models.PositiveIntegerField(default=3)

    # Statistical Safety Stock & Policy
    service_level = models.FloatField(default=0.95, help_text="e.g. 0.90, 0.95, 0.99")
    service_level_z = models.FloatField(default=1.645, help_text="Z-score for service level")
    safety_stock = models.PositiveIntegerField(default=0)
    reorder_point = models.PositiveIntegerField(default=0)
    target_stock = models.PositiveIntegerField(default=0)
    recommended_quantity = models.PositiveIntegerField(default=0)
    recommended_reorder_qty = models.PositiveIntegerField(default=0)  # Maintained for backward compatibility

    # Manual Overrides & Audit
    manual_quantity = models.PositiveIntegerField(null=True, blank=True)
    override_reason = models.TextField(blank=True)
    overridden_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='recommendation_overrides'
    )
    overridden_at = models.DateTimeField(null=True, blank=True)

    # Financial Estimates
    unit_cost = models.DecimalField(max_digits=10, decimal_places=2, default=Decimal('0.00'))
    estimated_purchase_cost = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal('0.00'))

    # Classifications & Status
    priority = models.CharField(
        max_length=15,
        choices=Priority.choices,
        default=Priority.MEDIUM,
        db_index=True
    )
    urgency_level = models.CharField(
        max_length=15,
        choices=Urgency.choices,
        default=Urgency.MEDIUM,
        db_index=True
    )
    status = models.CharField(
        max_length=20,
        choices=Status.choices,
        default=Status.PENDING,
        db_index=True
    )
    reorder_status = models.CharField(
        max_length=25,
        choices=ReorderStatus.choices,
        default=ReorderStatus.STOCK_ADEQUATE,
        db_index=True
    )
    stock_movement_type = models.CharField(
        max_length=25,
        choices=MovementType.choices,
        default=MovementType.NORMAL,
        db_index=True
    )
    stockout_risk = models.CharField(
        max_length=15,
        choices=StockoutRisk.choices,
        default=StockoutRisk.LOW,
        db_index=True
    )
    days_of_cover = models.FloatField(null=True, blank=True)
    estimated_stockout_date = models.DateField(null=True, blank=True)
    replenishment_timing = models.CharField(
        max_length=25,
        choices=ReplenishmentTiming.choices,
        default=ReplenishmentTiming.MONITOR,
        db_index=True
    )
    demand_spike_alert = models.BooleanField(default=False)
    demand_spike_info = models.JSONField(default=dict, blank=True)

    # Explanations & Viva Audit
    reason = models.TextField(blank=True)
    rationale = models.TextField(blank=True)
    action_taken = models.BooleanField(default=False)
    calculation_breakdown = models.JSONField(default=dict, blank=True)

    # PO Integration & Traceability
    purchase_order = models.ForeignKey(
        'inventory.PurchaseOrder',
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='advisor_recommendations'
    )
    is_stale_prediction = models.BooleanField(default=False)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = 'purchase_recommendations'
        verbose_name = 'Purchase Recommendation'
        verbose_name_plural = 'Purchase Recommendations'
        ordering = ['-priority', '-created_at']
        indexes = [
            models.Index(fields=['shop', 'status']),
            models.Index(fields=['shop', 'priority']),
            models.Index(fields=['product', 'status']),
        ]

    def save(self, *args, **kwargs):
        # Synchronize legacy aliases automatically
        if self.recommended_quantity and not self.recommended_reorder_qty:
            self.recommended_reorder_qty = self.recommended_quantity
        elif self.recommended_reorder_qty and not self.recommended_quantity:
            self.recommended_quantity = self.recommended_reorder_qty

        if self.reason and not self.rationale:
            self.rationale = self.reason
        elif self.rationale and not self.reason:
            self.reason = self.rationale

        if self.priority != self.urgency_level:
            if self.urgency_level and self.urgency_level != self.Urgency.MEDIUM and self.priority == self.Priority.MEDIUM:
                self.priority = self.urgency_level
            elif self.priority and self.priority in dict(self.Urgency.choices):
                self.urgency_level = self.priority
            elif self.urgency_level:
                self.priority = self.urgency_level

        # Calculate authoritative financial cost
        effective_qty = self.manual_quantity if self.manual_quantity is not None else self.recommended_quantity
        if effective_qty and self.unit_cost:
            self.estimated_purchase_cost = Decimal(str(effective_qty)) * self.unit_cost

        super().save(*args, **kwargs)

    @property
    def effective_quantity(self):
        """Returns manual override quantity if present, otherwise recommended quantity."""
        return self.manual_quantity if self.manual_quantity is not None else self.recommended_quantity

    def __str__(self):
        qty = self.effective_quantity
        return f"Restock {qty}x {self.product.name} ({self.get_priority_display()}) - [{self.get_status_display()}]"


class ProductRecommendation(models.Model):
    """
    Customer-facing smart recommendations (Exam kits, popular stationery, recurring essentials).
    """
    class RecType(models.TextChoices):
        GENERAL = 'GENERAL', 'General'
        ACADEMIC = 'ACADEMIC', 'Academic'
        POPULAR = 'POPULAR', 'Popular'
        SIMILAR = 'SIMILAR', 'Similar'
        BUY_AGAIN = 'BUY_AGAIN', 'Buy Again'

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='product_recommendations',
        null=True,
        blank=True
    )
    product = models.ForeignKey(
        'products.Product',
        on_delete=models.CASCADE,
        related_name='customer_recommendations'
    )
    shop = models.ForeignKey(
        'shops.Shop',
        on_delete=models.CASCADE,
        related_name='customer_recommendations'
    )
    recommendation_type = models.CharField(
        max_length=20,
        choices=RecType.choices,
        default=RecType.GENERAL,
        db_index=True
    )
    score = models.DecimalField(max_digits=5, decimal_places=2, default=1.00)
    reason = models.CharField(max_length=255, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = 'product_recommendations'
        verbose_name = 'Product Recommendation'
        verbose_name_plural = 'Product Recommendations'
        indexes = [
            models.Index(fields=['recommendation_type', 'score']),
        ]

    def __str__(self):
        return f"[{self.get_recommendation_type_display()}] {self.product.name} (Score: {self.score})"
